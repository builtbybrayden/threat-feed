"""Detection briefs: one Markdown + one JSON file per candidate CVE.

The Markdown doubles as the body of the GitHub Issue work-queue item, so it's
written to be readable on its own.
"""

from __future__ import annotations

import json
from pathlib import Path

from .models import CveRecord

NVD_URL = "https://nvd.nist.gov/vuln/detail/"


def render_markdown(rec: CveRecord) -> str:
    d = rec.detection
    lines: list[str] = []
    lines.append(f"# {rec.cve_id} — detection brief")
    lines.append("")
    badges = []
    if rec.kev:
        badges.append("**KEV**")
    if rec.epss is not None:
        badges.append(f"EPSS {rec.epss:.0%}")
    if rec.cvss_score is not None:
        badges.append(f"CVSS {rec.cvss_score}")
    if d.has_poc:
        badges.append("has-PoC")
    if badges:
        lines.append(" · ".join(badges))
        lines.append("")

    lines.append("## Summary")
    lines.append(rec.description or "_No description available yet._")
    lines.append("")

    lines.append("## Affected")
    lines.append(f"- **Vendor / product:** {rec.vendor or '?'} / {rec.product or '?'}")
    lines.append(f"- **Affected versions:** {rec.affected_versions or '?'}")
    lines.append(f"- **Fixed in:** {rec.fixed_version or '?'}")
    if rec.cpes:
        lines.append(f"- **CPEs:** {len(rec.cpes)} (e.g. `{rec.cpes[0]}`)")
    lines.append("")

    lines.append("## Classification")
    lines.append(f"- **CWE:** {', '.join(rec.cwe) or '?'}")
    lines.append(f"- **CVSS vector:** `{rec.cvss_vector or '?'}`")
    lines.append(f"- **Remote (AV:N):** {d.remote_network}")
    lines.append(f"- **Likely HTTP:** {d.likely_http}")
    lines.append(f"- **Suggested template type:** `{d.suggested_template_type}`")
    lines.append("")

    lines.append("## Fingerprinting hints")
    if d.fingerprint_hints:
        for h in d.fingerprint_hints:
            lines.append(f"- {h}")
    else:
        lines.append("- _None derived; inspect the references below._")
    lines.append("")

    if d.test_target_hint:
        lines.append("## Test target")
        lines.append(f"- {d.test_target_hint}")
        lines.append("")

    if rec.poc_links:
        lines.append("## Proof-of-concept")
        for link in rec.poc_links[:10]:
            lines.append(f"- {link}")
        lines.append("")

    lines.append("## References")
    lines.append(f"- NVD: {NVD_URL}{rec.cve_id}")
    for ref in rec.references[:15]:
        tags = f" ({', '.join(ref.get('tags', []))})" if ref.get("tags") else ""
        lines.append(f"- {ref['url']}{tags}")
    lines.append("")

    lines.append("---")
    lines.append(
        "_Generated by the threat-feed detection-triage pipeline. "
        "Templates are drafted and validated only against local lab targets._"
    )
    return "\n".join(lines) + "\n"


def write_brief(rec: CveRecord, briefs_dir: str | Path) -> tuple[Path, Path]:
    """Write briefs/<CVE>.md and briefs/<CVE>.json; return their paths."""
    out = Path(briefs_dir)
    out.mkdir(parents=True, exist_ok=True)
    md_path = out / f"{rec.cve_id}.md"
    json_path = out / f"{rec.cve_id}.json"
    md_path.write_text(render_markdown(rec), encoding="utf-8")
    json_path.write_text(
        json.dumps(rec.to_dict(), ensure_ascii=False, indent=2, sort_keys=True),
        encoding="utf-8",
    )
    return md_path, json_path
